    public void View() {
        if (list.isEmpty()) {
            txtId.setText("");
            txtName.setText("");
            txtLop.setText("");
            return;
        }

        x = list.get(stt);
        this.txtId.setText(x.getId());
        this.txtName.setText(x.getName());
        this.txtLop.setText(x.getLop());
    }
    
    public void ViewTable(){
        DefaultTableModel model = (DefaultTableModel) this.tblSinhVien.getModel();
        model.setNumRows(0);
        int n = 1;
        for(SinhVien x:list){
            model.addRow(new Object[]{n++,x.getId(),x.getName(),x.getLop()});
        }
        this.tblSinhVien.setRowHeight(24);
    }
