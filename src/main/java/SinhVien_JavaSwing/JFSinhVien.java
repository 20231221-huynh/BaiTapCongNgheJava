    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:
        if (stt < 0 || stt >= list.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sinh viên cần sửa!");
            return;
        }
        String id = this.txtId.getText();
        String name = this.txtName.getText();
        String lop = this.txtLop.getText();
        list.set(stt, new SinhVien(id,name,lop));
        View();
        ViewTable();        
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
        if (stt < 0 || stt >= list.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sinh viên cần xóa!");
            return;
        } // Hỏi xác nhận trước khi xóa 
        int result = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn xóa sinh viên này không?", "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (result == JOptionPane.YES_OPTION) { // Xóa sinh viên đang được chọn 
            list.remove(stt); // Nếu danh sách vẫn còn sinh viên 
            if (!list.isEmpty()) { // Nếu vừa xóa sinh viên cuối cùng 
                if (stt >= list.size()) {
                    stt = list.size() - 1;
                }
                View();
            } else { // Nếu đã xóa hết sinh viên 
                stt = 0;
                txtId.setText("");
                txtName.setText("");
                txtLop.setText("");
            }
            ViewTable();
        }
    }//GEN-LAST:event_btnXoaActionPerformed

