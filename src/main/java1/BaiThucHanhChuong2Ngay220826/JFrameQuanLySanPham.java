    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        // TODO add your handling code here:                                                                              
        try {
            String maSP = txtMaSP.getText().trim();
            String tenSP = txtTenSP.getText().trim();
            String soLuongText = txtSoLuong.getText().trim();

            if (maSP.isEmpty() || tenSP.isEmpty() || soLuongText.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Vui lòng nhập đầy đủ thông tin!");
                return;
            }

            // Kiểm tra mã phải có cả chữ và số, tối đa 5 ký tự
            if (!kiemTraMaSP(maSP)) {
                JOptionPane.showMessageDialog(this,
                        "Mã hàng phải có cả chữ và số, tối đa 5 ký tự!");
                return;
            }

            // Kiểm tra mã trùng
            if (trungMaSP(maSP)) {
                JOptionPane.showMessageDialog(this,
                        "Mã hàng đã tồn tại!");
                return;
            }

            int soLuong = Integer.parseInt(soLuongText);

            if (soLuong < 0) {
                JOptionPane.showMessageDialog(this,
                        "Số lượng không được âm!");
                return;
            }

            // Tạo sản phẩm
            SanPham sp = new SanPham(maSP, tenSP, soLuong);

            danhSach.add(sp);

            // Hiển thị lên bảng
            hienThiDanhSach();

            // Hiển thị đơn giá tự động
            txtDonGia.setText(String.valueOf(sp.getDonGia()));

            JOptionPane.showMessageDialog(this,
                    "Thêm sản phẩm thành công!");

            // Sau khi thêm thì cho phép nhập mã mới
            xoaTrang();

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this,
                    "Số lượng phải là số!");
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:                                                                           
        try {
            String maSP = txtMaSP.getText().trim();
            String tenSP = txtTenSP.getText().trim();
            String soLuongText = txtSoLuong.getText().trim();

            if (maSP.isEmpty() || tenSP.isEmpty() || soLuongText.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Vui lòng nhập đầy đủ thông tin!");
                return;
            }

            int soLuong = Integer.parseInt(soLuongText);

            if (soLuong < 0) {
                JOptionPane.showMessageDialog(this,
                        "Số lượng không được âm!");
                return;
            }

            // Tìm sản phẩm theo mã
            for (SanPham sp : danhSach) {

                if (sp.getMaSP().equalsIgnoreCase(maSP)) {

                    // CHỈ sửa tên và số lượng
                    sp.setTenSP(tenSP);
                    sp.setSoLuong(soLuong);

                    // Đơn giá tự động thay đổi theo số lượng
                    txtDonGia.setText(String.valueOf(sp.getDonGia()));

                    // Cập nhật JTable
                    hienThiDanhSach();

                    JOptionPane.showMessageDialog(this,
                            "Sửa sản phẩm thành công!");

                    return;
                }
            }

            JOptionPane.showMessageDialog(this,
                    "Không tìm thấy sản phẩm!");

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this,
                    "Số lượng phải là số!");
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:                                       
        String maSP = txtMaSP.getText().trim();

        if (maSP.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Vui lòng nhập mã sản phẩm cần xóa!");
            return;
        }

        for (int i = 0; i < danhSach.size(); i++) {

            if (danhSach.get(i).getMaSP().equalsIgnoreCase(maSP)) {

                int luaChon = JOptionPane.showConfirmDialog(
                        this,
                        "Bạn có chắc muốn xóa sản phẩm này?",
                        "Xác nhận",
                        JOptionPane.YES_NO_OPTION
                );

                if (luaChon == JOptionPane.YES_OPTION) {

                    danhSach.remove(i);

                    hienThiDanhSach();

                    JOptionPane.showMessageDialog(this,
                            "Xóa sản phẩm thành công!");

                    xoaTrang();

                }

                return;
            }
        }

        JOptionPane.showMessageDialog(this,
                "Không tìm thấy mã sản phẩm!");
    }//GEN-LAST:event_btnXoaActionPerformed

