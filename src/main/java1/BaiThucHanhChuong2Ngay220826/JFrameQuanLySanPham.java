    private SanPham layThongTin() {
        String maSP = txtMaSP.getText().trim();
        String tenSP = txtTenSP.getText().trim();
        int soLuong = Integer.parseInt(txtSoLuong.getText().trim());

        return new SanPham(maSP, tenSP, soLuong);
    }

    private boolean kiemTraMaSP(String maSP) {
        return maSP.matches("(?=.*[a-zA-Z])(?=.*[0-9])[a-zA-Z0-9]{1,5}");
    }

    private boolean trungMaSP(String maSP) {
        for (SanPham sp : danhSach) {
            if (sp.getMaSP().equalsIgnoreCase(maSP)) {
                return true;
            }
        }

        return false;
    }

    private void hienThiDanhSach() {
        DefaultTableModel model = (DefaultTableModel) tableSanPham.getModel();

        model.setRowCount(0);

        for (SanPham sp : danhSach) {
            model.addRow(new Object[]{
                sp.getMaSP(),
                sp.getTenSP(),
                sp.getSoLuong(),
                sp.getDonGia(),
                sp.getTienHang()
            });
        }
    }

    private void xoaTrang() {
        txtMaSP.setText("");
        txtTenSP.setText("");
        txtSoLuong.setText("");
        txtDonGia.setText("");

        // Trạng thái nhập mới
        txtMaSP.setEnabled(true);
        txtTenSP.setEnabled(true);
        txtSoLuong.setEnabled(true);

        // Đơn giá luôn bị khóa
        txtDonGia.setEnabled(false);

        txtMaSP.requestFocus();
    }

